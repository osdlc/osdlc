#!/usr/bin/env python3
"""Regenerates tests/vectors.json with an implementation independent of the crate (Python's
hmac and hashlib), so the wire format is checked against something that shares no code with it.

    python3 -I tests/gen_vectors.py

The canonical string (ten lines joined by "\\n"): the literal det-signed-request/v1, direction,
audience, key id, epoch, METHOD, the request target exactly as sent (path and query, not sorted,
not decoded), ts, nonce, hex sha256 of the body. A change to the output is a wire-format change.
"""
import hashlib
import hmac
import json
import pathlib

NOW = 1767225600  # 2026-01-01T00:00:00Z
T = "tnt_0123456789abcdef"


def case(name, direction, aud, method, target, body, nonce, secret="vector-secret-0123456789abcdef0123456789abcdef", epoch=3, key=T, ts=NOW):
    body_hash = hashlib.sha256(body.encode()).hexdigest()
    canonical = "\n".join([
        "det-signed-request/v1", direction, aud, key, str(epoch), method, target, str(ts), nonce, body_hash,
    ])
    sig = hmac.new(secret.encode(), canonical.encode(), hashlib.sha256).hexdigest()
    return dict(name=name, key_id=key, epoch=epoch, secret=secret, direction=direction, audience=aud,
                method=method, path_and_query=target, body=body, ts=ts, nonce=nonce,
                canonical=canonical, body_sha256=body_hash, signature=sig)


cases = [
    case("control-whoami", "tenant-to-control", "control", "GET", "/control/v1/whoami", "", "aaaaaaaaaaaaaaaa0000000000000001"),
    case("control-heartbeat-query-as-sent", "tenant-to-control", "control", "POST",
         "/control/v1/heartbeat?z=2&a=1&&b=%41&a=0", '{"version":"0.1.0","busy":false}', "aaaaaaaaaaaaaaaa0000000000000002"),
    case("control-empty-query-marker", "tenant-to-control", "control", "GET", "/control/v1/whoami?", "", "aaaaaaaaaaaaaaaa0000000000000003"),
    case("trigger-ping", "control-to-tenant", T, "GET", "/internal/ping", "", "bbbbbbbbbbbbbbbb0000000000000001"),
    case("trigger-scheduled-with-body", "control-to-tenant", T, "POST", "/internal/scheduled/backup?run=7",
         '{"due":"2026-01-01T00:00:00Z"}', "bbbbbbbbbbbbbbbb0000000000000002"),
]

other = {"tenant-to-control": ("control-to-tenant", T), "control-to-tenant": ("tenant-to-control", "control")}
cross = []
for c in (cases[0], cases[3]):
    od, oa = other[c["direction"]]
    cross.append(dict(name=c["name"] + "-flipped-direction-same-audience", signed_by=c["name"],
                      verifier_direction=od, verifier_audience=c["audience"], expect="BadSignature"))
    cross.append(dict(name=c["name"] + "-at-the-other-listener", signed_by=c["name"],
                      verifier_direction=od, verifier_audience=oa, expect="BadSignature"))

doc = dict(
    comment="Golden vectors for signed-request v1. Generated by tests/gen_vectors.py with Python's hmac and "
            "hashlib (independent of the crate). Read by the crate's tests, and usable by any other implementation of the format. "
            "Never edit by hand: a change here is a wire-format change.",
    version=1, now=NOW, window_secs=60, signing=cases, cross_direction=cross)
out = pathlib.Path(__file__).with_name("vectors.json")
out.write_text(json.dumps(doc, indent=2) + "\n")
