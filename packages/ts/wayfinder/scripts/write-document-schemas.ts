// Writes src/document-schemas.generated.ts from the command tree: each
// document's schemaVersion, and the JSON Schema of the documents wayfinder
// does not declare in src/documents.ts (the shared commands', help, schema,
// error and version). Runs on the source, before `tsc`, so the build compiles
// what it writes. tests/commands.test.ts fails when the checked-in file is
// stale: run `node scripts/write-document-schemas.ts` and commit it.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import { ErrorDocumentSchema } from '@osdlc/cli-tool/command'
import { z } from 'zod'

import { createWayApp } from '../src/commands/index.ts'

/** The documents src/documents.ts declares as Zod; schema.ts builds those. */
const OWN = new Set(['catalog', 'query', 'run', 'providers'])

const toJson = (schema: z.ZodType): unknown =>
  z.toJSONSchema(schema, { io: 'input', unrepresentable: 'any' })

/** The source of src/document-schemas.generated.ts. */
export function generatedSource(): string {
  const app = createWayApp({ home: '/' }).app
  const versions: Record<string, number | undefined> = {}
  const schemas: Record<string, unknown> = {}
  for (const entry of app.schema()) {
    if (entry.kind === undefined || entry.kind in versions) continue
    versions[entry.kind] = entry.schemaVersion
    if (!OWN.has(entry.kind)) schemas[entry.kind] = entry.output
  }
  versions['error'] = 1
  schemas['error'] = toJson(ErrorDocumentSchema)
  versions['version'] = 1
  schemas['version'] = toJson(
    z.object({
      schemaVersion: z.literal(1),
      kind: z.literal('version'),
      name: z.string(),
      version: z.string(),
    }),
  )

  return (
    `// Generated by scripts/write-document-schemas.ts from the command tree. Do not edit.\n\n` +
    `/** The \`schemaVersion\` of each document \`way\` prints, by \`kind\`. */\n` +
    `export const GENERATED_VERSIONS = ${JSON.stringify(versions, null, 2)} as const\n\n` +
    `/** The JSON Schema of each document src/documents.ts does not declare, by \`kind\`. */\n` +
    `export const GENERATED_SCHEMAS: Readonly<Record<string, Readonly<Record<string, unknown>>>> = ${JSON.stringify(schemas, null, 2)}\n`
  )
}

/** The checked-in file. */
export const GENERATED_FILE = fileURLToPath(
  new URL('../src/document-schemas.generated.ts', import.meta.url),
)

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(GENERATED_FILE, generatedSource())
}
