/**
 * Writes src/scan/languages.generated.ts from vendor/scc/languages.json, the
 * language table of scc (https://github.com/boyter/scc) at the tag below. The
 * file is a straight transcription of the fields the lexer reads; choices of
 * our own (extension preferences, doc comments, boilerplate) live in
 * src/scan/overlay.ts.
 *
 *   node scripts/languages.ts            # rewrite the table (pnpm run languages)
 *   node scripts/languages.ts --check    # exit 1 if it is stale (pnpm run check:extra)
 *
 * To take a newer scc: replace the vendored file, update SCC_TAG and
 * SCC_SHA256, and run the script.
 */

import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { format, resolveConfig } from 'prettier'

const SCC_TAG = 'v4.1.0'
const SCC_SHA256 = 'c7afa3090864dafa40ab8dfcd358ce30fa8a45606777409c378f316802834d5b'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = join(ROOT, 'vendor', 'scc', 'languages.json')
const OUT = join(ROOT, 'src', 'scan', 'languages.generated.ts')

interface SccQuote {
  start: string
  end: string
  ignoreEscape?: boolean
  docString?: boolean
}
interface SccLanguage {
  extensions?: string[]
  filenames?: string[]
  shebangs?: string[]
  line_comment?: string[]
  multi_line?: [string, string][]
  nestedmultiline?: boolean
  quotes?: SccQuote[]
  escape?: string
}

const raw = readFileSync(SOURCE)
const sha = createHash('sha256').update(raw).digest('hex')
if (sha !== SCC_SHA256) {
  process.stderr.write(`languages: ${SOURCE} has sha256 ${sha}, expected ${SCC_SHA256}\n`)
  process.exit(1)
}

const table = Object.entries(JSON.parse(raw.toString('utf8')) as Record<string, SccLanguage>)
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([name, l]) => ({
    name,
    extensions: (l.extensions ?? []).map((e) => e.toLowerCase()),
    filenames: (l.filenames ?? []).map((f) => f.toLowerCase()),
    shebangs: l.shebangs ?? [],
    lineComments: l.line_comment ?? [],
    blockComments: l.multi_line ?? [],
    nestedBlocks: l.nestedmultiline === true,
    quotes: (l.quotes ?? []).map((q) => ({
      start: q.start,
      end: q.end,
      ...(q.ignoreEscape === true ? { raw: true } : {}),
      ...(q.docString === true ? { doc: true } : {}),
    })),
    ...(l.escape !== undefined ? { escape: l.escape } : {}),
  }))

const source = `// GENERATED by scripts/languages.ts from scc ${SCC_TAG} languages.json. DO NOT EDIT.
// scc is MIT licensed; see THIRD-PARTY-NOTICES.

import type { LanguageSyntax } from './syntax.ts'

export const SCC_LANGUAGES: readonly LanguageSyntax[] = ${JSON.stringify(table)}
`
const text = await format(source, { ...(await resolveConfig(OUT)), filepath: OUT })

if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== text) {
    process.stderr.write(`languages: ${OUT} is stale; run pnpm run languages\n`)
    process.exit(1)
  }
  process.stdout.write(`languages: ${OUT} is current\n`)
} else {
  writeFileSync(OUT, text)
  process.stdout.write(`languages: wrote ${table.length} languages to ${OUT}\n`)
}
