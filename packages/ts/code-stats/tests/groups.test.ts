import { describe, expect, test } from 'vitest'

import { createGroupClassifier, DEFAULT_RULES, kindInGroup, type FileFacts } from '../src/groups.ts'

const role = createGroupClassifier()
const code = (path: string, more: Partial<FileFacts> = {}) =>
  role({ path, category: 'programming', ...more })

describe('createGroupClassifier', () => {
  test('built-in rules', () => {
    expect(code('src/a.ts')).toBe('source')
    expect(code('src/a.test.ts')).toBe('tests')
    expect(code('pkg/tests/helpers.ts')).toBe('tests')
    expect(code('cmd/main_test.go')).toBe('tests')
    expect(role({ path: 'bun.lock', category: null })).toBe('generated')
    expect(role({ path: 'web/Cargo.lock', category: 'data' })).toBe('generated')
    expect(code('dist/app.min.js')).toBe('generated')
    expect(code('src/_generated/api.ts')).toBe('generated')
    expect(code('vendor/lib/x.go')).toBe('vendored')
    expect(code('a/node_modules/b/index.js')).toBe('vendored')
    expect(role({ path: 'README.md', category: 'prose' })).toBe('docs')
    expect(role({ path: 'skills/review/SKILL.md', category: 'prose' })).toBe('instructions')
    expect(role({ path: 'CLAUDE.md', category: 'prose' })).toBe('instructions')
    expect(role({ path: '.claude/agents/x.md', category: 'prose' })).toBe('instructions')
    expect(role({ path: 'tsconfig.json', category: 'data' })).toBe('other')
    expect(role({ path: 'LICENSE', category: 'legal' })).toBe('other')
    expect(role({ path: 'odd.xyz', category: null })).toBe('other')
  })

  test('a generated-file marker in the first lines', () => {
    expect(code('gen.go', { text: '// Code generated by x. DO NOT EDIT.\npackage x\n' })).toBe(
      'generated',
    )
    expect(code('a.ts', { text: `${'\n'.repeat(5)}// DO NOT EDIT\n` })).toBe('source')
    expect(code('a.ts', { text: '/** @generated */\n' })).toBe('generated')
    expect(code('a.ts', { text: '// generated by hand\n' })).toBe('source')
  })

  test('linguist attributes come before built-in rules, and false turns one off', () => {
    expect(code('src/a.ts', { attributes: { generated: true } })).toBe('generated')
    expect(code('src/a.ts', { attributes: { vendored: true } })).toBe('vendored')
    expect(code('src/a.ts', { attributes: { documentation: true } })).toBe('docs')
    expect(code('app.min.js', { attributes: { generated: false } })).toBe('source')
    expect(code('vendor/x.go', { attributes: { vendored: false } })).toBe('source')
  })

  test('caller rules come first', () => {
    const custom = createGroupClassifier({
      generated: ['cli/*.js'],
      docs: ['notes/**'],
      tests: ['checks/**'],
    })
    expect(custom({ path: 'cli/bundle.js', category: 'programming' })).toBe('generated')
    expect(
      custom({ path: 'cli/bundle.js', category: 'programming', attributes: { generated: false } }),
    ).toBe('generated')
    expect(custom({ path: 'notes/a.ts', category: 'programming' })).toBe('docs')
    expect(custom({ path: 'checks/a.ts', category: 'programming' })).toBe('tests')
  })
})

test('instruction prose counts as logic', () => {
  expect(kindInGroup('instructions', 'doc')).toBe('logic')
  expect(kindInGroup('instructions', 'comment')).toBe('comment')
  expect(kindInGroup('docs', 'doc')).toBe('doc')
})

test('the built-in rules cannot be changed by a caller', () => {
  expect(Object.isFrozen(DEFAULT_RULES)).toBe(true)
  expect(Object.isFrozen(DEFAULT_RULES.generated)).toBe(true)
})
