/**
 * `cli-tool-stamp-version`: writes a package's version into its source.
 *
 * A CLI's `build` runs it first, in the package directory. It reads
 * `package.json` there and writes `src/version.generated.ts` with one export,
 * `VERSION`. The CLI passes that to `defineApp` or `runMain`, so `--version`
 * needs no read of `package.json` at run time and still answers when the CLI
 * is bundled or compiled to one file. `prepublishOnly` runs `build`, so a
 * published tarball always carries its own version.
 *
 * The file is committed, so a fresh checkout typechecks without a build. A
 * version bump must run it again; `--check` exits 1 when the file is stale.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

/** Where the version is written, relative to the package directory. */
export const DEFAULT_OUT = 'src/version.generated.ts'

/** The source of the generated file for `version`, in the repo's Prettier style. */
export function versionSource(version: string): string {
  if (/['\\\n]/.test(version))
    throw new Error(`version ${JSON.stringify(version)} cannot be quoted`)
  return (
    '// Generated by cli-tool-stamp-version from package.json. Do not edit.\n\n' +
    "/** This package's version, from its package.json when it was built. */\n" +
    `export const VERSION = '${version}'\n`
  )
}

/** What one run did: wrote the file, found it current, or (under `--check`) found it stale. */
export type StampResult = 'written' | 'current' | 'stale'

/**
 * Stamp the package in `dir`. Writes only when the content changes. With
 * `check`, writes nothing and reports `stale` when the file would change.
 */
export function stampVersion(
  dir: string,
  options: { out?: string; check?: boolean } = {},
): StampResult {
  const pkg = JSON.parse(readFileSync(resolve(dir, 'package.json'), 'utf8')) as {
    version?: unknown
  }
  if (typeof pkg.version !== 'string' || pkg.version === '') {
    throw new Error(`${resolve(dir, 'package.json')}: no "version" string`)
  }
  const out = resolve(dir, options.out ?? DEFAULT_OUT)
  const want = versionSource(pkg.version)
  let have: string | undefined
  try {
    have = readFileSync(out, 'utf8')
  } catch {
    have = undefined
  }
  if (have === want) return 'current'
  if (options.check === true) return 'stale'
  writeFileSync(out, want)
  return 'written'
}

/**
 * The bin's main: `cli-tool-stamp-version [--check] [--out <path>]`. Returns
 * the exit code: 2 for a bad argument, 1 for a stale file under `--check` or a
 * package.json or output path that cannot be read or written.
 */
export function stampVersionMain(
  argv: readonly string[],
  cwd: string,
  write: (line: string) => void,
): number {
  let check = false
  let out: string | undefined
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]
    if (arg === '--check') check = true
    else if (arg === '--out') {
      out = argv[++i]
      if (out === undefined) {
        write('cli-tool-stamp-version: --out needs a path')
        return 2
      }
    } else {
      write(`cli-tool-stamp-version: unknown argument '${arg}'`)
      write('usage: cli-tool-stamp-version [--check] [--out <path>]')
      return 2
    }
  }
  let result: StampResult
  try {
    result = stampVersion(cwd, out === undefined ? { check } : { out, check })
  } catch (err) {
    write(`cli-tool-stamp-version: ${err instanceof Error ? err.message : String(err)}`)
    return 1
  }
  if (result === 'stale') {
    write(
      `cli-tool-stamp-version: ${out ?? DEFAULT_OUT} does not match package.json; ` +
        'run cli-tool-stamp-version and commit it',
    )
    return 1
  }
  return 0
}
