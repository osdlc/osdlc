// The checklist in docs/planning/BEELINE.md, generated from the plan by scripts/build-data.mjs.
// Imports name the .ts file, so that the script can load this module under plain Node.
import type { Plan, PlanTask } from './plan.ts'
import { indexPlan, isNextUp, STATUS_ORDER, type PlanIndex } from './work.ts'

export const BEELINE_START = '<!-- beeline:start -->'
export const BEELINE_END = '<!-- beeline:end -->'

/** Who does a task: the owner when it waits on the owner, else an agent. */
export type Doer = 'agent' | 'owner'

export function doerOf(task: PlanTask): Doer {
  return task.status === 'owner' ? 'owner' : 'agent'
}

export interface BeelineGroups {
  /** Not done, and every task it waits on is done. In STATUS_ORDER, then plan order. */
  nextUp: PlanTask[]
  /** Not done, and waiting on a task that is not done. In plan order. */
  waiting: PlanTask[]
  done: PlanTask[]
}

/** The tasks of the beeline milestones, in milestone order and then each milestone's task order. */
export function beelineTasks(index: PlanIndex): PlanTask[] {
  return index.plan.milestones.filter((m) => m.beeline).flatMap((m) => index.tasksOf.get(m.id) ?? [])
}

export function beelineGroups(index: PlanIndex): BeelineGroups {
  const tasks = beelineTasks(index)
  const open = tasks.filter((t) => t.status !== 'done')
  const rank = (t: PlanTask) => STATUS_ORDER.indexOf(t.status)
  return {
    nextUp: open.filter((t) => isNextUp(index, t)).sort((a, b) => rank(a) - rank(b)),
    waiting: open.filter((t) => !isNextUp(index, t)),
    done: tasks.filter((t) => t.status === 'done'),
  }
}

/** The ids in a task's `after` that are not done. */
export function openAfter(index: PlanIndex, task: PlanTask): number[] {
  return task.after.filter((id) => index.task.get(id)?.status !== 'done')
}

/** One checklist line. `href` is the link to the task's record. */
export function checklistItem(index: PlanIndex, task: PlanTask, href: string): string {
  const done = task.status === 'done'
  const parts = [`[${task.id} ${task.title}](${href})`, index.statusLabel(task.status)]
  if (!done) parts.push(doerOf(task))
  if (task.prs.length > 0) parts.push(task.prs.map((pr) => `[${pr.label}](${pr.url})`).join(', '))
  const waits = openAfter(index, task)
  if (waits.length > 0) parts.push(`waits on ${waits.join(', ')}`)
  return `- [${done ? 'x' : ' '}] ${parts.join(' · ')}`
}

/** The Markdown between the markers: next up first, then waiting, then done. */
export function beelineChecklist(plan: Plan, href: (task: PlanTask) => string): string {
  const index = indexPlan(plan)
  const milestones = plan.milestones.filter((m) => m.beeline).map((m) => `\`${m.id}\``)
  const groups = beelineGroups(index)
  const sections: [string, PlanTask[]][] = [
    ['Next up', groups.nextUp],
    ['Waiting', groups.waiting],
    ['Done', groups.done],
  ]
  const lines = [
    `Generated by \`pnpm build-data\` from the tasks in the beeline milestones: ${milestones.join(', ')}. Do not edit it by hand.`,
    '',
    'Each item: the task, its status, who does it, its pull requests, and the tasks it still waits on.',
  ]
  for (const [title, tasks] of sections) {
    if (tasks.length === 0) continue
    lines.push('', `### ${title} (${tasks.length})`, '', ...tasks.map((t) => checklistItem(index, t, href(t))))
  }
  return lines.join('\n')
}

/** `text` with the block between the markers replaced, or null when it lacks either marker. */
export function replaceBeeline(text: string, block: string): string | null {
  const start = text.indexOf(BEELINE_START)
  const end = text.indexOf(BEELINE_END)
  if (start === -1 || end === -1 || end < start) return null
  return `${text.slice(0, start + BEELINE_START.length)}\n\n${block}\n\n${text.slice(end)}`
}
